"""Experiment queue runner.

usage: python src/run_queue.py --queue configs/queue.yaml [--status] [--max-gpu 2] [--dry-run]
Steps (configs/queue.yaml):
  - name: E0m_v2
    cmd: "{PY} -u -W ignore src/train.py --config configs/E0m_v2.yaml"   # {PY} = this interpreter
    depends_on: [..]
    gpu: true                      # at most --max-gpu gpu steps run concurrently; cpu steps are unlimited
    post: train | fusion | none    # train: evaluate(clean+noisy) -> leaderboard -> PROGRESS -> commit "exp(<name>): ..."; fusion: leaderboard+commit
    optional: true                 # skip (not fail) if its config file does not exist yet (generated by an earlier step)
    config: configs/X.yaml         # for post=train (default configs/<name>.yaml)
    done: results/<name>/metrics.json   # completion marker (default); existing marker => step skipped (resume)
Failure: logged (logs/queue/<name>.log), dependents marked dep_failed, independent steps continue.
State: logs/queue/state.json (used by --status).
"""
import argparse
import datetime as dt
import json
import subprocess
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PY = sys.executable
QLOG = ROOT / "logs" / "queue"
STATE = QLOG / "state.json"


def now():
    return dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def sh(cmd, log, cwd=ROOT):
    with open(log, "a", encoding="utf-8") as f:
        f.write(f"\n$ {cmd}\n")
        f.flush()
        return subprocess.call(cmd, shell=True, cwd=str(cwd), stdout=f, stderr=subprocess.STDOUT)


def git_commit(paths, msg, log):
    sh("git add " + " ".join(f'"{p}"' for p in paths), log)
    rc = sh(f'git commit -q -m "{msg}"', log)
    if rc == 0:
        import os
        with open(log, "a", encoding="utf-8") as f:
            subprocess.call("git push origin HEAD", shell=True, cwd=str(ROOT), stdout=f, stderr=subprocess.STDOUT, env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
    return rc


def one_liner(name):
    m = json.loads((ROOT / "results" / name / "metrics.json").read_text(encoding="utf-8"))
    parts = [f"test macro-F1 {m['macro_f1']:.4f}"]
    if m.get("danger_recall") is not None:
        parts.append(f"emerg recall {m['danger_recall']:.3f}")
    if m.get("emergency_group_recall") is not None:
        parts.append(f"group {m['emergency_group_recall']:.3f}")
    if m.get("background_fa_rate") is not None:
        parts.append(f"bg FA {m['background_fa_rate']:.3f}")
    if m.get("noisy_snr10"):
        parts.append(f"SNR10 {m['noisy_snr10']['macro_f1']:.3f}")
    if m.get("test", {}).get("reject_rate_non_target_events") is not None:
        parts.append(f"reject non-target {m['test']['reject_rate_non_target_events']:.3f} bg {m['test']['reject_rate_background']:.3f}")
    return ", ".join(parts)


def progress(name, step, line):
    with open(ROOT / "PROGRESS.md", "a", encoding="utf-8") as f:
        f.write(f"\n## [{now()[:16]}] queue: {name}\n- 작업: `{step.get('cmd', '')[:160]}`\n- 결과: {line}\n- 다음 할 일: 큐 계속 (`python src/run_queue.py --status`)\n")


def post_train(name, step, log):
    cfg = step.get("config", f"configs/{name}.yaml")
    if sh(f'"{PY}" -u -W ignore src/evaluate.py --config {cfg} --eval-set all', log) != 0:
        return False
    sh(f'"{PY}" -I src/make_leaderboard.py', log)
    line = one_liner(name)
    progress(name, step, line)
    paths = [f"results/{name}", f"logs/{name}.summary.md", "results/LEADERBOARD.md", "PROGRESS.md"]
    git_commit(paths, f"exp({name}): {line.split(',')[0]}", log)
    return True


def post_fusion(name, step, log):
    sh(f'"{PY}" -I src/make_leaderboard.py', log)
    done = ROOT / step.get("done", f"results/{name}/metrics.json")
    line = one_liner(name) if done.exists() and done.name == "metrics.json" else "done"
    progress(name, step, line)
    paths = [p for p in [f"results/{name}", f"logs/{name}.summary.md", "results/LEADERBOARD.md", "PROGRESS.md", "configs", "docs"] if (ROOT / p).exists()]
    git_commit(paths, f"exp({name}): {line.split(',')[0]}", log)
    return True


def marker(step):
    return ROOT / step.get("done", f"results/{step['name']}/metrics.json")


def inputs_ready(step, by):
    """All dependency markers must exist on disk (status alone is not enough)."""
    return all(marker(by[d]).exists() or by[d].get("optional") for d in step.get("depends_on", []))


def load_state(steps):
    st = json.loads(STATE.read_text(encoding="utf-8")) if STATE.exists() else {}
    for s in steps:
        st.setdefault(s["name"], {"status": "pending"})
        if st[s["name"]]["status"] == "running":  # previous runner died: relaunch
            st[s["name"]] = {"status": "pending", "note": "relaunched after interrupted run"}
        if st[s["name"]]["status"] in ("done", "skipped", "failed", "dep_failed") and not marker(s).exists() and not (
                st[s["name"]]["status"] == "skipped" and s.get("optional")):  # output gone (or stale state): run again
            st[s["name"]] = {"status": "pending", "note": "marker missing -> rerun"}
    return st


def save_state(st):
    STATE.write_text(json.dumps(st, ensure_ascii=False, indent=1), encoding="utf-8")


def print_status(steps, st):
    rows = [(s["name"], st[s["name"]]["status"], st[s["name"]].get("start", ""), st[s["name"]].get("end", ""), st[s["name"]].get("minutes", "")) for s in steps]
    w = max(len(r[0]) for r in rows)
    print(f"{'step':<{w}}  {'status':<11} {'start':<19} {'end':<19} min")
    for r in rows:
        print(f"{r[0]:<{w}}  {r[1]:<11} {r[2]:<19} {r[3]:<19} {r[4]}")
    tot = sum(float(st[s["name"]].get("minutes") or 0) for s in steps)
    print(f"total minutes so far: {tot:.0f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--queue", default="configs/queue.yaml")
    ap.add_argument("--max-gpu", type=int, default=2)
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--poll", type=int, default=20)
    a = ap.parse_args()
    q = yaml.safe_load(open(ROOT / a.queue, encoding="utf-8"))
    steps = q["steps"]
    by = {s["name"]: s for s in steps}
    QLOG.mkdir(parents=True, exist_ok=True)
    if a.status:  # read-only view of the runner's state file
        st = json.loads(STATE.read_text(encoding="utf-8")) if STATE.exists() else {}
        for s in steps:
            st.setdefault(s["name"], {"status": "pending"})
        print_status(steps, st)
        return
    st = load_state(steps)
    for s in steps:  # resume: completion marker present AND every input marker present (a stale marker alone does not count)
        done = marker(s)
        if done.exists() and st[s["name"]]["status"] != "done":
            if inputs_ready(s, by):
                st[s["name"]] = {"status": "done", "note": "marker existed", "end": now()}
            else:
                print(f"[{now()}] stale marker ignored for {s['name']}: {done} (inputs missing) -> removing", flush=True)
                done.unlink()
                st[s["name"]] = {"status": "pending"}
    save_state(st)
    running = {}  # name -> (Popen, log, t0)
    t_queue = time.time()
    while True:
        # reap
        for name, (proc, log, t0) in list(running.items()):
            if proc.poll() is None:
                continue
            step = by[name]
            minutes = (time.time() - t0) / 60
            ok = proc.returncode == 0
            if ok and step.get("post", "none") == "train":
                ok = post_train(name, step, log)
            elif ok and step.get("post") == "fusion":
                ok = post_fusion(name, step, log)
            done = ROOT / step.get("done", f"results/{name}/metrics.json")
            ok = ok and done.exists()
            st[name].update({"status": "done" if ok else "failed", "end": now(), "minutes": round(minutes, 1), "rc": proc.returncode})
            print(f"[{now()}] {'DONE' if ok else 'FAILED'} {name} ({minutes:.1f} min)", flush=True)
            del running[name]
            save_state(st)
        # mark dep_failed
        for s in steps:
            if st[s["name"]]["status"] == "pending" and any(st[d]["status"] in ("failed", "dep_failed") for d in s.get("depends_on", [])):
                st[s["name"]]["status"] = "dep_failed"
        # launch
        n_gpu = sum(1 for n in running if by[n].get("gpu"))
        for s in steps:
            name = s["name"]
            if st[name]["status"] != "pending" or name in running:
                continue
            if not all(st[d]["status"] in ("done", "skipped") for d in s.get("depends_on", [])):  # skipped optional steps satisfy deps
                continue
            if not inputs_ready(s, by):  # dependency marked done but its output file is missing -> stay pending
                continue
            if s.get("optional") and s.get("config") and not (ROOT / s["config"]).exists():
                st[name].update({"status": "skipped", "note": "config not generated", "end": now()})
                print(f"[{now()}] SKIP {name} (optional, no config)", flush=True)
                continue
            if s.get("gpu") and n_gpu >= a.max_gpu:
                continue
            cmd = s["cmd"].replace("{PY}", f'"{PY}"')
            log = QLOG / f"{name}.log"
            if a.dry_run:
                print("would run:", name, cmd)
                st[name]["status"] = "done"
                continue
            # resume shortcut: training already finished (best.pt + history) -> only post-processing
            if s.get("post") == "train" and (ROOT / "checkpoints" / name / "best.pt").exists() and (ROOT / "results" / name / "train_history.json").exists():
                cmd = "echo reuse-existing-checkpoint"
            with open(log, "a", encoding="utf-8") as f:
                f.write(f"\n==== {now()} {name}\n$ {cmd}\n")
            proc = subprocess.Popen(cmd, shell=True, cwd=str(ROOT), stdout=open(log, "a", encoding="utf-8"), stderr=subprocess.STDOUT)
            running[name] = (proc, log, time.time())
            st[name].update({"status": "running", "start": now()})
            if s.get("gpu"):
                n_gpu += 1
            print(f"[{now()}] START {name}", flush=True)
            save_state(st)
        if not running and all(st[s["name"]]["status"] != "pending" for s in steps):
            break
        if not running and not any(st[s["name"]]["status"] == "pending" and all(st[d]["status"] in ("done", "skipped") for d in s.get("depends_on", [])) and inputs_ready(s, by) for s in steps):
            print(f"[{now()}] nothing runnable (remaining steps blocked by failures)", flush=True)
            break
        if not running and a.dry_run:
            break
        time.sleep(a.poll)
    st["_total_minutes"] = round((time.time() - t_queue) / 60, 1)
    save_state(st)
    print_status(steps, st)
    print(f"[{now()}] QUEUE FINISHED in {st['_total_minutes']} min", flush=True)


if __name__ == "__main__":
    main()
