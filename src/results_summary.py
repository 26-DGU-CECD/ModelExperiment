"""Final report: docs/results_summary.md from results/*/metrics.json (v2 labels only unless --all), configs, queue state.
usage: python src/results_summary.py [--all]"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[0] = str(ROOT)

import yaml  # noqa: E402

from src.make_leaderboard import LABELS, fmt, load, table, table_a, table_b, table_d  # noqa: E402


HOMOGENEOUS = ("G_", "S_mn10_", "F_seed_", "F_mn10_", "F_effat_", "oracle_mn10", "overlap_")


def is_homogeneous(m):
    return m["experiment"].startswith(HOMOGENEOUS)


def table_c_full(ms, section=None):
    rows = []
    for m in sorted(ms, key=lambda m: m.get("macro_f1") or 0, reverse=True):
        if m.get("condition") == "specialist":
            continue
        if section == "main" and is_homogeneous(m):
            continue
        if section == "homogeneous" and not is_homogeneous(m):
            continue
        g = m.get("test", {}).get("group", {})
        rows.append([m["experiment"], m.get("condition", "-"), m.get("method", "-"), fmt(m.get("macro_f1")), fmt(m.get("accuracy")),
                     fmt(m.get("danger_recall")), fmt(g.get("emergency_group_recall")), fmt(g.get("emergency_group_precision")),
                     fmt(g.get("caution_group_recall")), fmt(g.get("daily_group_recall")), fmt(g.get("group_accuracy")),
                     fmt(m.get("background_fa_rate")), fmt(m.get("bg_fa_strict")),
                     fmt((m.get("noisy_snr20") or {}).get("macro_f1")), fmt((m.get("noisy_snr15") or {}).get("macro_f1")), fmt((m.get("noisy_snr10") or {}).get("macro_f1"))])
    return table(["experiment", "condition", "method", "macro-F1", "acc", "emerg recall", "emerg grp recall", "emerg grp prec", "caution grp recall",
                  "daily grp recall", "group acc", "bg FA", "bg FA strict", "SNR20", "SNR15", "SNR10"], rows)


def config_summary():
    rows = []
    for p in sorted((ROOT / "configs").glob("*.yaml")):
        if p.name in ("labels.yaml", "groups.yaml", "queue.yaml") or p.name.startswith("smoke"):
            continue
        c = yaml.safe_load(open(p, encoding="utf-8"))
        if not isinstance(c, dict) or "model" not in c:
            continue
        rows.append([c.get("exp_name", p.stem), c["model"], c.get("mode", "-"), c.get("group_set", "-") if c.get("mode") == "specialist" else "-",
                     str(c.get("epochs", "-")), str(c.get("lr", "-")), str(c.get("batch_size", "-")), str(c.get("sampler", {}).get("cap", "-")),
                     "KD" if c.get("teacher") else ("init:" + Path(c["init_from"]).parent.name if c.get("init_from") else "-"),
                     "on" if (c.get("aug") or {}).get("musan") else "off"])
    return table(["exp", "model", "mode", "groups", "epochs", "lr", "batch", "cap/class", "teacher/init", "MUSAN aug"], rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true", help="include v1-label results")
    a = ap.parse_args()
    ms = load()
    if not a.all:
        ms = [m for m in ms if m.get("label_version") == "v2"]
    labels = yaml.safe_load(open(ROOT / "configs" / "labels.yaml", encoding="utf-8"))
    groups = yaml.safe_load(open(ROOT / "configs" / "groups.yaml", encoding="utf-8"))
    state = json.loads((ROOT / "logs" / "queue" / "state.json").read_text(encoding="utf-8")) if (ROOT / "logs" / "queue" / "state.json").exists() else {}
    total = state.get("_total_minutes") or sum(float(v.get("minutes") or 0) for k, v in state.items() if isinstance(v, dict))
    md = ["# Results summary", "", f"labels: {labels.get('version', 'v1')} ({len(labels['labels'])} classes). "
          f"{len(ms)} experiments. Queue total: {total:.0f} min ({total / 60:.1f} h). Generated by `python src/results_summary.py`.", "",
          "## Groups", ""]
    for gs, g in groups.items():
        if isinstance(g, dict):
            md.append(f"- **{gs}**: " + "; ".join(f"{k} = {v['labels']}" for k, v in g.items() if isinstance(v, dict)))
    md += ["", "## A. generalist per-class F1 (test)", "", table_a(ms),
           "## B. specialist vs generalist", "", table_b(ms),
           "## C. condition summary (incl. group recall, noisy)", "", "### heterogeneous (efficientat / yamnet / mnv4) + ablations", "", table_c_full(ms, "main"),
           "### homogeneous (same backbone family: seeds, mn10 specialists, EfficientAT variants, error-overlap oracles)", "", table_c_full(ms, "homogeneous"),
           "## D. operating points", "", table_d(ms),
           "## Config summary", "", config_summary(),
           "## Queue steps", "", table(["step", "status", "minutes"], [[k, v.get("status", "-"), str(v.get("minutes", "-"))] for k, v in state.items() if isinstance(v, dict)])]
    (ROOT / "docs" / "results_summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(ms)} experiments -> docs/results_summary.md (total {total:.0f} min)")


if __name__ == "__main__":
    main()
